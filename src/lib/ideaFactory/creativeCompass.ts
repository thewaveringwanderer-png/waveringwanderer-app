
export function formatCreativeCompassForPrompt() {
  return `
WW CREATIVE COMPASS

The Creative Compass exists to maximise long-term artistic progress.

Previous engines determine whether an idea is creative, realistic and engaging.

The Creative Compass determines whether it is the best direction.

It asks:

"Which idea leaves the artist in a stronger position after creating it?"

The Compass does not optimise for views alone.

It optimises for careers.

Never expose this reasoning.

==================================================
1. DIRECTION TEST
==================================================

Ask:

Does this move the artist towards the career they are trying to build?

Or does it simply create another post?

Reject ideas that generate activity without meaningful progress.

==================================================
2. IDENTITY TEST
==================================================

Ask:

Will this strengthen recognition of this artist?

Would repeated exposure make this artist easier to recognise?

Does it reinforce the Identity Kit?

==================================================
3. CREATIVE ASSET TEST
==================================================

Ask:

Does this leave something behind?

Examples:

- recurring format
- recognisable visual
- signature mechanic
- storytelling format
- audience ritual
- repeatable structure
- visual language
- world-building element

Prefer ideas that build assets over ideas that disappear.

==================================================
4. COMPOUNDING TEST
==================================================

Imagine this type of content was repeated for six months.

Would it become stronger?

Would fans begin recognising it?

Would it become part of the artist's identity?

Prefer ideas that gain value through repetition.

==================================================
5. OPPORTUNITY TEST
==================================================

Ask:

Does this use something unique about this artist?

Or could almost anyone make it?

Whenever possible, choose ideas that transform the artist's own reality into a creative advantage.

==================================================
6. LEGACY TEST
==================================================

Imagine the artist looks back one year from now.

Would they be glad they spent creative energy making this?

Or would they rather have spent that effort building something with greater long-term value?

==================================================
THE COMPASS PRINCIPLE
==================================================

Creative work should leave the artist in a stronger position than before it existed.

A good idea creates content.

A great idea creates momentum.

An exceptional idea builds the artist's world.

Whenever multiple concepts are equally strong, choose the one that creates the greatest long-term value.
`.trim()
}